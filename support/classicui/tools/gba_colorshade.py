def widen6(c6):
    return (c6 << 2) | (c6 >> 4)            # GBA.sv: {c, c[5:4]}


def shade(mode, r5, g5, b5):
    """One 15-bit colour through mode 1..4; returns 8-bit R, G, B."""
    lin = LIN[(mode - 1) * 32:mode * 32]
    m = MULT[(mode - 1) * 9:mode * 9]
    bd = BORDER[(mode - 1) * 64:mode * 64]
    out = []
    for c in range(3):
        s = m[c * 3] * lin[r5] + m[c * 3 + 1] * lin[g5] + m[c * 3 + 2] * lin[b5]
        v = int(s / 1024)                     # VHDL "/": truncates toward zero
        v = 0 if v < 0 else 1023 if v > 1023 else v
        q = 0
        for t in range(1, 64):
            if v > bd[t]:
                q = t
        out.append(widen6(q))
    return tuple(out)


def apply_modify_colors(rows, name):
    """A raw GBA frame (Modify Colors=Off: 6-bit {c5, c5[4]} widened) through a profile."""
    mode = MODES.get(name)
    if not mode:
        return rows
    cache = {}
    out = []
    for r in rows:
        o = []
        for p in r:
            if p not in cache:
                cache[p] = shade(mode, p[0] >> 3, p[1] >> 3, p[2] >> 3)
            o.append(cache[p])
        out.append(o)
    return out
