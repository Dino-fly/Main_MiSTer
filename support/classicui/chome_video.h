/*
  Classic Home - video looks.

  A short curated list of presets instead of MiSTer's filter/mask/gamma knobs.
  Each look drives two machines: the scaler, through a real MiSTer preset file
  applied with video_loadPreset() (which persists per core), and the running
  core's own display options, matched by NAME against its CONF_STR and never
  saved into its config - see the preset table in chome_video.cpp for why the
  colour work moved core-side for GB and GBA, and what stays with the scaler
  (the pixel grid, drawn by a polyphase filter so it lands on core pixel
  boundaries at any scale - the one thing a shadow mask cannot promise).

  The filter coefficients, shadow masks, gamma LUTs and .gbp palettes the
  presets reference are generated by vp_install() rather than assumed to be on
  the SD card, so the looks work on a stock install without the community
  filter packs. Files we generated are regenerated when their content changes;
  files without our marker belong to the user and are never touched.

  Every class offers one entry that turns all processing off (Sharp for the CRT
  classes, None for handhelds - None also resets the core-side effects).

  What a look does divides into colour and structure, and the division is data,
  not a special case: the palette and the colour correction are one column of the
  preset table, the pixel grid, the drop shadow and the panel's ghosting another.
  On an analog display only the colour half is applied - see vp_output_is_analog()
  below, and the table's own note about why.

  Previews are illustrations rendered in software from the same parameters, not
  captures of a running core.
*/

